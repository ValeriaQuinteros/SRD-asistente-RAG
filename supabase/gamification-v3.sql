create table if not exists public.patient_rewards (
  patient_id uuid primary key references public.profiles(id) on delete cascade,
  total_points integer not null default 0 check (total_points >= 0),
  current_streak integer not null default 0 check (current_streak >= 0),
  best_streak integer not null default 0 check (best_streak >= 0),
  level text not null default 'Comenzando',
  last_completed_date date,
  updated_at timestamptz not null default now()
);

create table if not exists public.achievements (
  id text primary key,
  name text not null,
  description text not null,
  icon text not null default '🏅',
  required_sessions integer not null check (required_sessions > 0),
  points_reward integer not null default 0 check (points_reward >= 0)
);

create table if not exists public.patient_achievements (
  patient_id uuid not null references public.profiles(id) on delete cascade,
  achievement_id text not null references public.achievements(id) on delete cascade,
  earned_at timestamptz not null default now(),
  primary key (patient_id, achievement_id)
);

create table if not exists public.reward_events (
  id bigint generated by default as identity primary key,
  patient_id uuid not null references public.profiles(id) on delete cascade,
  session_id uuid not null unique references public.sessions(id) on delete cascade,
  base_points integer not null default 100,
  bonus_points integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists idx_patient_achievements_patient on public.patient_achievements(patient_id);
create index if not exists idx_reward_events_patient on public.reward_events(patient_id);

