alter table public.patient_rewards enable row level security;
alter table public.achievements enable row level security;
alter table public.patient_achievements enable row level security;
alter table public.reward_events enable row level security;

drop policy if exists "patient_rewards_select" on public.patient_rewards;
create policy "patient_rewards_select" on public.patient_rewards
for select to authenticated
using (
  patient_id = auth.uid()
  or public.current_role() = 'admin'
  or (
    public.current_role() = 'kinesiologo'
    and exists (
      select 1 from public.profiles p
      where p.id = patient_rewards.patient_id
        and p.assigned_kinesiologo_id = auth.uid()
    )
  )
);

drop policy if exists "achievements_select" on public.achievements;
create policy "achievements_select" on public.achievements
for select to authenticated
using (true);

drop policy if exists "patient_achievements_select" on public.patient_achievements;
create policy "patient_achievements_select" on public.patient_achievements
for select to authenticated
using (
  patient_id = auth.uid()
  or public.current_role() = 'admin'
  or (
    public.current_role() = 'kinesiologo'
    and exists (
      select 1 from public.profiles p
      where p.id = patient_achievements.patient_id
        and p.assigned_kinesiologo_id = auth.uid()
    )
  )
);

drop policy if exists "reward_events_select" on public.reward_events;
create policy "reward_events_select" on public.reward_events
for select to authenticated
using (
  patient_id = auth.uid()
  or public.current_role() = 'admin'
  or (
    public.current_role() = 'kinesiologo'
    and exists (
      select 1 from public.profiles p
      where p.id = reward_events.patient_id
        and p.assigned_kinesiologo_id = auth.uid()
    )
  )
);

-- El navegador solo necesita LEER recompensas.
-- Las escrituras las realizan triggers SECURITY DEFINER del servidor.
grant select on public.patient_rewards to authenticated;
grant select on public.achievements to authenticated;
grant select on public.patient_achievements to authenticated;
grant select on public.reward_events to authenticated;

-- Sin permisos directos de escritura para authenticated.
revoke insert, update, delete on public.patient_rewards from authenticated;
