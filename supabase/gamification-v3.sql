-- Crear fila de recompensas para los pacientes ya existentes.
insert into public.patient_rewards (patient_id)
select id
from public.profiles
where role = 'paciente'
on conflict (patient_id) do nothing;

create or replace function public.reward_level(completed_sessions integer)
returns text
language sql
immutable
as $$
  select case
    when completed_sessions >= 50 then 'Imparable'
    when completed_sessions >= 25 then 'Gran progreso'
    when completed_sessions >= 10 then 'Comprometido'
    when completed_sessions >= 5 then 'Constante'
    when completed_sessions >= 1 then 'En progreso'
    else 'Comenzando'
  end;
$$;

-- Garantiza que cada perfil paciente tenga su registro de recompensas.
create or replace function public.ensure_patient_reward_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.role = 'paciente' then
    insert into public.patient_rewards (patient_id)
    values (new.id)
    on conflict (patient_id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_ensure_patient_rewards on public.profiles;
create trigger trg_ensure_patient_rewards
after insert or update of role on public.profiles
for each row execute procedure public.ensure_patient_reward_profile();

-- Recompensas del servidor:
-- 100 puntos base por sesión completada.
-- Los bonos por logros se entregan una sola vez.
-- Una misma sesión no puede entregar puntos dos veces gracias a reward_events.session_id UNIQUE.
create or replace function public.award_completed_session()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  event_id bigint;
  reward_date date;
  old_streak integer := 0;
  old_best integer := 0;
  old_last_date date;
  new_streak integer := 1;
  completed_count integer := 0;
  total_bonus integer := 0;
  achievement_row record;
  inserted_rows integer := 0;
begin
  if new.status <> 'completada' then
    return new;
  end if;

  if tg_op = 'UPDATE' and old.status = 'completada' then
    return new;
  end if;

  insert into public.reward_events (patient_id, session_id, base_points, bonus_points)
  values (new.patient_id, new.id, 100, 0)
  on conflict (session_id) do nothing
  returning id into event_id;

  -- Si la sesión ya recibió recompensa, no volvemos a sumar.
  if event_id is null then
    return new;
  end if;

  insert into public.patient_rewards (patient_id)
  values (new.patient_id)
  on conflict (patient_id) do nothing;

  select current_streak, best_streak, last_completed_date
  into old_streak, old_best, old_last_date
  from public.patient_rewards
  where patient_id = new.patient_id
  for update;

  reward_date := coalesce(new.ended_at, now())::date;

  if old_last_date is null then
    new_streak := 1;
  elsif reward_date = old_last_date then
    -- Varias sesiones el mismo día mantienen la misma racha.
    new_streak := greatest(old_streak, 1);
  elsif reward_date = old_last_date + 1 then
    new_streak := old_streak + 1;
  else
    -- No se muestra como castigo: simplemente comienza una nueva racha.
    new_streak := 1;
  end if;

  update public.patient_rewards
  set
    total_points = total_points + 100,
    current_streak = new_streak,
    best_streak = greatest(old_best, new_streak),
    last_completed_date = greatest(coalesce(old_last_date, reward_date), reward_date),
    updated_at = now()
  where patient_id = new.patient_id;

  select count(*)
  into completed_count
  from public.sessions
  where patient_id = new.patient_id
    and status = 'completada';

  for achievement_row in
    select *
    from public.achievements
    where required_sessions <= completed_count
    order by required_sessions
  loop
    insert into public.patient_achievements (patient_id, achievement_id)
    values (new.patient_id, achievement_row.id)
    on conflict (patient_id, achievement_id) do nothing;

    get diagnostics inserted_rows = row_count;
    if inserted_rows = 1 then
      total_bonus := total_bonus + achievement_row.points_reward;
    end if;
  end loop;

  update public.patient_rewards
  set
    total_points = total_points + total_bonus,
    level = public.reward_level(completed_count),
    updated_at = now()
  where patient_id = new.patient_id;

  update public.reward_events
  set bonus_points = total_bonus
  where id = event_id;

  return new;
end;
$$;

drop trigger if exists trg_award_completed_session on public.sessions;
create trigger trg_award_completed_session
after insert or update of status on public.sessions
for each row execute procedure public.award_completed_session();

