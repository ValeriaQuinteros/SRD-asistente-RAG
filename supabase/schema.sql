-- SRD - Sala de Rehabilitación Deportiva
-- Ejecutar completo en Supabase SQL Editor.

create extension if not exists "pgcrypto";

do $$ begin
  create type public.user_role as enum ('admin', 'kinesiologo', 'paciente');
exception when duplicate_object then null;
end $$;

do $$ begin
  create type public.session_status as enum ('en_progreso', 'completada', 'cancelada');
exception when duplicate_object then null;
end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text,
  phone text,
  role public.user_role not null default 'paciente',
  active boolean not null default true,
  assigned_kinesiologo_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.exercises (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text,
  instructions text,
  active boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sensors (
  id uuid primary key default gen_random_uuid(),
  exercise_id uuid not null references public.exercises(id) on delete cascade,
  name text not null,
  body_zone text not null,
  min_value numeric not null,
  max_value numeric not null,
  unit text not null default 'grados',
  created_at timestamptz not null default now(),
  constraint sensor_range_valid check (min_value <= max_value)
);

create table if not exists public.assignments (
  id uuid primary key default gen_random_uuid(),
  patient_id uuid not null references public.profiles(id) on delete cascade,
  exercise_id uuid not null references public.exercises(id) on delete restrict,
  kinesiologo_id uuid references public.profiles(id) on delete set null,
  series integer not null default 3 check (series > 0),
  repetitions integer not null default 10 check (repetitions > 0),
  frequency text not null default '3 veces por semana',
  start_date date,
  end_date date,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.sessions (
  id uuid primary key default gen_random_uuid(),
  patient_id uuid not null references public.profiles(id) on delete cascade,
  exercise_id uuid not null references public.exercises(id) on delete restrict,
  assignment_id uuid references public.assignments(id) on delete set null,
  kinesiologo_id uuid references public.profiles(id) on delete set null,
  status public.session_status not null default 'en_progreso',
  started_at timestamptz not null default now(),
  ended_at timestamptz
);

create table if not exists public.sensor_readings (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.sessions(id) on delete cascade,
  exercise_id uuid not null references public.exercises(id) on delete cascade,
  sensor_id uuid not null references public.sensors(id) on delete restrict,
  value numeric not null,
  unit text not null,
  in_range boolean,
  recorded_at timestamptz not null default now()
);

create index if not exists idx_profiles_role on public.profiles(role);
create index if not exists idx_profiles_kine on public.profiles(assigned_kinesiologo_id);
create index if not exists idx_sensors_exercise on public.sensors(exercise_id);
create index if not exists idx_assignments_patient on public.assignments(patient_id);
create index if not exists idx_sessions_patient on public.sessions(patient_id);
create index if not exists idx_readings_session on public.sensor_readings(session_id);

-- Crear perfil automáticamente cuando se crea un usuario desde Auth.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, email, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    new.email,
    coalesce((new.raw_user_meta_data->>'role')::public.user_role, 'paciente')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Funciones auxiliares para RLS.
create or replace function public.current_role()
returns public.user_role
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid();
$$;

