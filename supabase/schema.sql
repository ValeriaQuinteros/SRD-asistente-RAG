-- Profiles
drop policy if exists "profiles_select" on public.profiles;
create policy "profiles_select" on public.profiles
for select to authenticated
using (
  id = auth.uid()
  or public.current_role() = 'admin'
  or (public.current_role() = 'kinesiologo' and assigned_kinesiologo_id = auth.uid())
);

drop policy if exists "profiles_update_admin" on public.profiles;
create policy "profiles_update_admin" on public.profiles
for update to authenticated
using (public.current_role() = 'admin' or id = auth.uid())
with check (public.current_role() = 'admin' or id = auth.uid());

-- Exercises
drop policy if exists "exercises_select_staff_or_assigned_patient" on public.exercises;
create policy "exercises_select_staff_or_assigned_patient" on public.exercises
for select to authenticated
using (
  public.current_role() in ('admin','kinesiologo')
  or exists (
    select 1 from public.assignments a
    where a.exercise_id = exercises.id and a.patient_id = auth.uid() and a.active = true
  )
);

drop policy if exists "exercises_insert_staff" on public.exercises;
create policy "exercises_insert_staff" on public.exercises
for insert to authenticated
with check (public.current_role() in ('admin','kinesiologo'));

drop policy if exists "exercises_update_staff" on public.exercises;
create policy "exercises_update_staff" on public.exercises
for update to authenticated
using (public.current_role() in ('admin','kinesiologo'))
with check (public.current_role() in ('admin','kinesiologo'));

-- Sensors
drop policy if exists "sensors_select" on public.sensors;
create policy "sensors_select" on public.sensors
for select to authenticated
using (
  public.current_role() in ('admin','kinesiologo')
  or exists (
    select 1 from public.assignments a
    where a.exercise_id = sensors.exercise_id and a.patient_id = auth.uid() and a.active = true
  )
);

drop policy if exists "sensors_manage_staff" on public.sensors;
create policy "sensors_manage_staff" on public.sensors
for all to authenticated
using (public.current_role() in ('admin','kinesiologo'))
with check (public.current_role() in ('admin','kinesiologo'));

-- Assignments
drop policy if exists "assignments_select" on public.assignments;
create policy "assignments_select" on public.assignments
for select to authenticated
using (
  public.current_role() = 'admin'
  or kinesiologo_id = auth.uid()
  or patient_id = auth.uid()
);

drop policy if exists "assignments_insert_staff" on public.assignments;
create policy "assignments_insert_staff" on public.assignments
for insert to authenticated
with check (
  public.current_role() = 'admin'
  or (public.current_role() = 'kinesiologo' and kinesiologo_id = auth.uid())
);

drop policy if exists "assignments_update_staff" on public.assignments;
create policy "assignments_update_staff" on public.assignments
for update to authenticated
using (public.current_role() = 'admin' or kinesiologo_id = auth.uid())
with check (public.current_role() = 'admin' or kinesiologo_id = auth.uid());

-- Sessions
drop policy if exists "sessions_select" on public.sessions;
create policy "sessions_select" on public.sessions
for select to authenticated
using (public.current_role() = 'admin' or kinesiologo_id = auth.uid() or patient_id = auth.uid());

drop policy if exists "sessions_insert" on public.sessions;
create policy "sessions_insert" on public.sessions
for insert to authenticated
with check (
  public.current_role() = 'admin'
  or patient_id = auth.uid()
  or kinesiologo_id = auth.uid()
);

drop policy if exists "sessions_update" on public.sessions;
create policy "sessions_update" on public.sessions
for update to authenticated
using (public.current_role() = 'admin' or kinesiologo_id = auth.uid() or patient_id = auth.uid())
with check (public.current_role() = 'admin' or kinesiologo_id = auth.uid() or patient_id = auth.uid());

-- Readings
drop policy if exists "readings_select" on public.sensor_readings;
create policy "readings_select" on public.sensor_readings
for select to authenticated
using (
  public.current_role() = 'admin'
  or exists (select 1 from public.sessions s where s.id = sensor_readings.session_id and (s.kinesiologo_id = auth.uid() or s.patient_id = auth.uid()))
);

drop policy if exists "readings_insert" on public.sensor_readings;
create policy "readings_insert" on public.sensor_readings
for insert to authenticated
with check (
  exists (select 1 from public.sessions s where s.id = session_id and (s.patient_id = auth.uid() or s.kinesiologo_id = auth.uid()))
);

-- Regla de máximo 3 sensores por ejercicio.
create or replace function public.limit_exercise_sensors()
returns trigger
language plpgsql
as $$
declare sensor_count integer;
begin
  select count(*) into sensor_count from public.sensors where exercise_id = new.exercise_id and id <> coalesce(new.id, gen_random_uuid());
  if sensor_count >= 3 then
    raise exception 'Un ejercicio no puede tener más de 3 sensores';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_limit_exercise_sensors on public.sensors;
create trigger trg_limit_exercise_sensors
before insert on public.sensors
for each row execute procedure public.limit_exercise_sensors();
